from __future__ import annotations

from typing import Any

from app.models.model_catalog import get_model_catalog
from app.scoring.objective_scorer import (
    score_objective_suitability,
)
from app.scoring.statistical_scorer import (
    score_statistical_suitability,
)


TOP_N_MODELS = 3


def _to_dict(value: Any) -> Any:
    if value is None:
        return None

    if isinstance(value, dict):
        return {
            key: _to_dict(item)
            for key, item in value.items()
        }

    if isinstance(value, list):
        return [
            _to_dict(item)
            for item in value
        ]

    if hasattr(value, "model_dump"):
        return value.model_dump()

    if hasattr(value, "dict"):
        return value.dict()

    if hasattr(value, "__dict__"):
        return {
            key: _to_dict(item)
            for key, item in vars(value).items()
            if not key.startswith("_")
        }

    return value


def _extract_phase3_statistics(
    session: Any,
) -> Any:
    """
    Read the statistical result generated by Phase 3.
    """

    result = getattr(
        session,
        "statistical_result",
        None,
    )

    if result:
        return _to_dict(result)

    return {}


def _extract_phase4_objective(
    session: Any,
) -> dict:
    """
    Read the objective interpretation generated
    by Phase 4.
    """

    objective = getattr(
        session,
        "phase4_objective",
        None,
    )

    if objective:
        result = _to_dict(objective)

        if isinstance(result, dict):
            return result

    return {}


def _clean_score_details(
    details: Any,
) -> list[dict]:
    """
    Keep only the information required by the
    Phase 5 score breakdown UI.

    Statistical:
        Test name + score / 7

    Objective:
        Component name + score / maximum
    """

    cleaned = []

    if not isinstance(details, list):
        return cleaned

    for item in details:

        if not isinstance(item, dict):
            continue

        name = (
            item.get("name")
            or item.get("factor")
            or ""
        )

        if not name:
            continue

        score = float(
            item.get("score", 0.0)
        )

        maximum = float(
            item.get(
                "maximum",
                item.get(
                    "max_score",
                    0.0,
                ),
            )
        )

        cleaned.append(
            {
                "factor": str(name),
                "name": str(name),
                "score": round(score, 2),
                "maximum": round(maximum, 2),
                "max_score": round(maximum, 2),
            }
        )

    return cleaned


def _build_recommendations(
    phase3_statistics: Any,
    objective: dict,
) -> list[dict]:
    """
    Evaluate all 10 configured models internally.

    Only the Top 3 are returned to the frontend.
    """

    statistical_scores = (
        score_statistical_suitability(
            phase3_statistics
        )
    )

    objective_scores = (
        score_objective_suitability(
            objective
        )
    )

    recommendations = []

    for model in get_model_catalog():

        name = model["name"]

        statistical = statistical_scores.get(
            name,
            {
                "score": 0.0,
                "maximum": 70.0,
                "details": [],
            },
        )

        objective_result = objective_scores.get(
            name,
            {
                "score": 0.0,
                "maximum": 30.0,
                "details": [],
            },
        )

        statistical_score = float(
            statistical.get(
                "score",
                0.0,
            )
        )

        objective_score = float(
            objective_result.get(
                "score",
                0.0,
            )
        )

        final_score = (
            statistical_score
            + objective_score
        )

        recommendations.append(
            {
                "model": name,

                "display_name": model.get(
                    "display_name",
                    name,
                ),

                "category": model.get(
                    "category"
                ),

                "description": model.get(
                    "description"
                ),

                "statistical_score": round(
                    statistical_score,
                    2,
                ),

                "statistical_maximum": 70.0,

                "statistical_max_score": 70.0,

                "objective_score": round(
                    objective_score,
                    2,
                ),

                "objective_maximum": 30.0,

                "objective_max_score": 30.0,

                "final_score": round(
                    final_score,
                    2,
                ),

                "final_maximum": 100.0,

                "final_max_score": 100.0,

                "statistical_details":
                    _clean_score_details(
                        statistical.get(
                            "details",
                            [],
                        )
                    ),

                "objective_details":
                    _clean_score_details(
                        objective_result.get(
                            "details",
                            [],
                        )
                    ),
            }
        )

    # ---------------------------------------------------------
    # Rank all 10 models internally
    # ---------------------------------------------------------

    recommendations.sort(
        key=lambda item: (
            item["final_score"],
            item["objective_score"],
            item["statistical_score"],
        ),
        reverse=True,
    )

    for index, recommendation in enumerate(
        recommendations,
        start=1,
    ):
        recommendation["rank"] = index

    # ---------------------------------------------------------
    # Return ONLY TOP 3
    # ---------------------------------------------------------

    return recommendations[:TOP_N_MODELS]


def generate_phase5_recommendations(
    session: Any,
    dataset_id: str,
) -> dict:

    phase3_statistics = (
        _extract_phase3_statistics(
            session
        )
    )

    objective = (
        _extract_phase4_objective(
            session
        )
    )

    recommendations = (
        _build_recommendations(
            phase3_statistics,
            objective,
        )
    )

    recommended_model = (
        recommendations[0]
        if recommendations
        else None
    )

    return {
        "dataset_id": str(
            dataset_id
        ),

        "recommended_model":
            recommended_model,

        "recommendations":
            recommendations,

        "statistical_maximum":
            70.0,

        "objective_maximum":
            30.0,

        "final_maximum":
            100.0,

        "objective":
            objective,

        "generated":
            True,
    }